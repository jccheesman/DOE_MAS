def group_sites_by_region(bulk_fuel_csv_path: str, shapefile_path: str, region_column: str = "NAME") -> str:

    """ Takes bulk fuel facility data and Alaska regional shapefile, performs spatial join,
    and returns a dictionary mapping each facility to its region.

    Parameters:
        bulk_fuel_csv_path: Path to the CSV file containing bulk fuel facility data
        shapefile_path: Path to the Alaska Energy Development Regions shapefile
        region_column: Name of the region column in the shapefile (default: None)

    Return: Two formatted dictionaries - bulk_fuel_dict_with_regions and unassigned_dict """

    # Process input data
    bulk_fuel_data = pd.read_csv(bulk_fuel_csv_path, usecols =['ASTFacilityID','ASTFacilityLongitude', 'ASTFacilityLatitude', 'Delivery_method']) # Bulk fuel facility sites
    regional_shapefile = gpd.read_file(shapefile_path)                                                                                            # Regional Shapefile
    bulk_fuel_data = bulk_fuel_data.dropna(axis=0, how='all', subset=['ASTFacilityLongitude', 'ASTFacilityLatitude'])                             # Drop rows with missing coordinates

    # Convert site coordinates to Point geometries
    geometry = [Point(xy) for xy in zip(bulk_fuel_data['ASTFacilityLongitude'],bulk_fuel_data['ASTFacilityLatitude'])]

    # Create a GeoDataFrame from sites
    bulk_fuel_sites_gdf = gpd.GeoDataFrame(bulk_fuel_data, geometry=geometry)
    bulk_fuel_sites_gdf.set_crs(epsg=4326, inplace=True)                  ######## Could change crs here!!

    # Check and align CRS
    if bulk_fuel_sites_gdf.crs != regional_shapefile.crs:
        bulk_fuel_sites_gdf = bulk_fuel_sites_gdf.to_crs(regional_shapefile.crs)

    # Perform spatial join - finds which region each site falls into
    # how ='left' will keep all sites even if they are not assigned a region
    # predicate = 'within' checks if points are within the polygons
    sites_with_regions = gpd.sjoin(bulk_fuel_sites_gdf,regional_shapefile,how='left',predicate='within')

    # Assigning regions to each site
    for index, row in sites_with_regions.iterrows():
        facility_id = row['ASTFacilityID'] # Get facility ID
        region_value = row.get(region_column, None) # Get region value
        # Convert region from NaN to None, if needed
        if pd.isna(region_value):
            region_value = None
            unassigned_dict[facility_id]={ # Add to unassigned dictionary
                'FacilityID': facility_id,
                'Longitude': row['ASTFacilityLongitude'],
                'Latitude': row['ASTFacilityLatitude'],
                'Delivery_method': row['Delivery_method'],
                'Region': 'Unassigned'
            }
        else:  # Adds all sites with a set region
          bulk_fuel_dict_with_regions[facility_id] = {
              'FacilityID': facility_id,
              'Longitude': row['ASTFacilityLongitude'],
              'Latitude': row['ASTFacilityLatitude'],
              'Delivery_method': row['Delivery_method'],
              'Region': region_value}


    # Save to CSV in current working directory
    result_df = pd.DataFrame(sites_with_regions.drop(columns='geometry'))
    result_df.to_csv('sites_with_regions.csv', index=False)

    # Calculate statistics
    total_sites = len(bulk_fuel_dict_with_regions)
    sites_with_region = sum(1 for v in bulk_fuel_dict_with_regions.values() if v['Region'] is not None)
    sites_without_region = total_sites - sites_with_region

    # Return summary statistics
    summary = f"""
    Regionalization Complete!

    Total Facilities: {total_sites}
    Facilities Assigned to Regions: {sites_with_region}
    Facilities Without Region Assignment: {sites_without_region}

    Results saved to 'sites_with_regions.csv'

    """

    print(summary)
    # Return global dictionaries
    return bulk_fuel_dict_with_regions, unassigned_dict


def get_region_statistics(csv_path: str = 'sites_with_regions.csv') -> str:
    """
    Analyzes the regionalization results and provides statistics by region.
    Parameters:
        csv_path: Path to the CSV file with region assignments
    Return: String with regional statistics
    """
    df = pd.read_csv(csv_path)

    # Count facilities per region
    region_counts = df.groupby('NAME').size().sort_values(ascending=False)

    stats = "Facilities per Region:\n"
    for region, count in region_counts.items():
        stats += f"{region}: {count} facilities\n"

    return stats

def structure_regional_dictionaries (bulk_fuel_dict_with_regions: dict):
    '''Function to create a regional nested dictionary for each region in Alaska'''

    temp_regional_dict = {} # Create an overall dictionary to store sites by region
    # Accesses each bulk fuel facility site using the facility_id
    for facility_id, data in bulk_fuel_dict_with_regions.items():
        region = data.get('Region')
        if region is None:
          continue
        if region not in temp_regional_dict:        # Create region key if it doesn't exist
          temp_regional_dict[region] = {}           # Initiates new dictionary for a region
        temp_regional_dict[region][facility_id] = { # Add facility to this region's dictionary
          'FacilityID': facility_id,
          'Longitude': data['Longitude'],
          'Latitude': data['Latitude'],
          'Delivery_method': data['Delivery_method']}

    return temp_regional_dict

def plot_by_regions(reg_dict: dict, unassigned_dict: dict):
  ''' Function to plot by regions, using separate colors'''
  # Create a figure and axis
  fig, ax = plt.subplots(figsize=(10, 10))

  colors = ['#e6194B','#3cb44b','#ffe119','#4363d8','#f58231','#911eb4','#42d4f4','#f032e6','#bfef45','#fabed4','#469990','#dcbeff','#9A6324','#808000']

  # Plot each region with a different color
  for region, sites in reg_dict.items():
      x = [site['Longitude'] for site in sites.values()]
      y = [site['Latitude'] for site in sites.values()]
      ax.scatter(x, y, color=colors.pop(), label=region)

