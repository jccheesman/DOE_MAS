#@title Setting up main function to execute the crewAI

def run_regionalization(bulk_fuel_csv_path: str, shapefile_path: str, region_column: str = None):
    """Execute the CrewAI workflow to regionalize bulk fuel facilities.

    Parameters:
        bulk_fuel_csv_path: Path to bulk fuel facility CSV
        shapefile_path: Path to Alaska regions shapefile
        region_column: Column name for region in shapefile

    Return: Dictionary with facility assignments"""

    group_sites_by_region(bulk_fuel_csv_path, shapefile_path, region_column)      # Group sites by region using shapefile and XY coordinates
    regional_dict = structure_regional_dictionaries(bulk_fuel_dict_with_regions)  # Create a structured regional dictionary
    plot_by_regions(regional_dict, unassigned_dict)                               # Plot sites by region, including unassigned facilities
    final_regionalized_dict = group_by_delivery_method(regional_dict)             # Group by delivery method within each region

    print("Running CrewAI approach...")
    print("="*50)
    # Sets up crewAI
    crew = Crew(
        agents=[delivery_method_agent,logistics_agent],
        tasks=[delivery_task,logistics_task],
        process=Process.sequential,
        verbose=True)

    # Run the crew
    result = crew.kickoff(inputs={'final_regionalized_dict': final_regionalized_dict}) # Pass path as string

    # Print statements
    print("\n" + "="*50)
    print("CREW EXECUTION COMPLETE")
    print("="*50)
    print(result)

    # Return the dictionary that was stored globally by the tool
    return final_regionalized_dict

# Main Function call
def main():
    region_column = 'NAME'
