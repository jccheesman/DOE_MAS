#Function to convert the RegionalTourResult to a dictionary
def convert_results_for_crewai(results: Dict[str, Dict[str, RegionalTourResult]]) -> dict:
    """Convert RegionalTourResult namedtuples to dictionaries for CrewAI.
    
    Input structure: results[region][delivery_method] = RegionalTourResult
    Output structure: Same nested structure but with dicts instead of namedtuples
    """
    converted = {}
    
    for region, delivery_methods in results.items():
        converted[region] = {}
        
        for dm, result in delivery_methods.items():
            # Check if already converted (is a dict, not RegionalTourResult)
            if isinstance(result, dict):
                converted[region][dm] = result
            else:
                # Convert RegionalTourResult to dictionary
                converted[region][dm] = {
                    'region': result.region,
                    'tour': [{'longitude': city.real, 'latitude': city.imag} for city in result.tour],
                    'length': result.length,
                    'secs': result.secs,
                    'num_sites': result.num_sites
                }
    
    return converted


