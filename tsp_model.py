""" Run TSP algorithm on each region separately.
    Parameters:
    - input_dict: nested dictionary of all regions and bulk fuel sites
    - tsp_algo: TSP algorithm to use
    - optimize: whether to optimize the TSP solution
    Returns: {region: RegionalTourResult} """

def run_regional_tsp(input_dict: dict, tsp_algo=greedy_tsp, optimize=True) -> Dict[str, RegionalTourResult]:

    """Run TSP algorithm for each region and delivery method group.
    Returns: Nested dictionary: results[region][delivery_method] = RegionalTourResult"""

    results = {} # Initialize a overall dictionary to store results
    for region in input_dict.keys():
        #print(f"Processing region {region}")

        #Initialize a dictionary to store each RegionalTourResult for each tour in regions
        results[region] = {}

        for dm in input_dict[region].keys():
            #print(f"Processing delivery method {dm} in {region}")
            try:
                # region_cities, delivery_methods, facility_lookup = parse_regional_locations(input_dict, region)
                group_cities, delivery_method_region = parse_regional_locations(input_dict, region, dm)
                if len(group_cities) == 0:
                    print(f"Skipping region {region}: no sites")
                    continue
                t0 = time.perf_counter() # Starts timer
                tour = tsp_algo(group_cities) #Runs TSP algorithm on individual region
                if optimize: # Looks at Optimization functions if optimize=True
                    tour = opt2(tour)
                t1 = time.perf_counter() #Ends timer
                length = tour_length(tour)
                # Result that is put into the result nested dictionary (nested by region and delivery method)
                results[region][dm] = RegionalTourResult(
                    region=region,
                    tour=tour,
                    length= length,
                    secs=t1 - t0,
                    num_sites=len(group_cities))
            except Exception as e:
                print(f"Error processing region {region}: {e}")

    return results

